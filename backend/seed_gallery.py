def _row_exists(db: Session, city: str, spot: str) -> bool:
    return (
        db.query(CityImage.id)
        .filter(CityImage.city == city, CityImage.spot == spot)
        .first()
        is not None
    )


def seed():
    Base.metadata.create_all(bind=engine)
    db = SessionLocal()
    inserted = skipped = 0
    missing = 0
    try:
        for city, items in GALLERY.items():
            for idx, (filename, spot, category, desc) in enumerate(items):
                path = SCENERY_DIR / filename
                if not path.exists():
                    print(f"  [缺图] {city} / {spot}: {filename}")
                    missing += 1
                    continue
                if _row_exists(db, city, spot):
                    skipped += 1
                    continue
                db.add(
                    CityImage(
                        city=city,
                        spot=spot,
                        filename=filename,
                        category=category,
                        description=desc,
                        sort=idx,
                    )
                )
                inserted += 1
        db.commit()
        total = db.query(CityImage).count()
        city_cnt = db.query(CityImage.city).distinct().count()
        print(f"\n✅ 城市图片库: 新增 {inserted} / 已存在 {skipped} / 缺图 {missing}")
        print(f"   当前库: {city_cnt} 个城市 / {total} 张图片")
        print(f"   GALLERY 规划: {len(GALLERY)} 个城市 / {sum(len(v) for v in GALLERY.values())} 张图")
    finally:
        db.close()


if __name__ == "__main__":
    seed()
